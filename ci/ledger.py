#!/usr/bin/env python3
"""Build-control ledgers as per-WP fragments (WP-161). Dependency-free.

The three ledgers (`LEDGER_implementations.md`, `LEDGER_quirks.md`,
`LEDGER_vanilla_files.md`) used to be single files that every work package
edited at the same anchor, so every pair of open PRs conflicted on them (55 of
64 conflicted merge-ups in the 60 PRs before WP-161 were ledger-only). Now each
entry is its own file:

    Ladruno_implementation/ledger/<kind>/<KEY>-<slug>.md     kind = implementations | quirks | vanilla
    Ladruno_implementation/ledger/<kind>/_template.md        the ledger's intro + conventions

KEY is `WP-<n>` for work-package entries; content older than the WP era uses
`ADR-<n>`, `PR-<n>` or `LEGACY`. A fragment is YAML front matter + a markdown
body, and the body is exactly what the old ledger held:

    implementations   one table row (section: table), or one build-history bullet (section: history)
    quirks            one `###` (or legacy `##`) entry, heading included
    vanilla           one PR's rows, one row per file (table: main | upstreamable)

`build` renders the three ledgers into `Ladruno_implementation/ledger/_build/`
(gitignored; CI uploads it as the `ledgers` artifact). The committed
`LEDGER_*.md` are short stubs so `[[LEDGER_quirks]]` wiki-links still resolve.

Commands:
    python ci/ledger.py build [--out DIR]
        Render all three ledgers. Newest WP first for implementations rows and
        quirks (by `date`), then the migrated entries in their old order; vanilla
        rows are grouped by file.
    python ci/ledger.py split [--ref REV]
        ONE-TIME migration: read the full LEDGER_*.md (working tree, or REV),
        write the templates + one fragment per entry, replace the ledgers with
        stubs. Refuses to split a stub. Keeps fragments that are not migrated
        (no `legacy_seq`), e.g. a WP's own fragment written before the split.
    python ci/ledger.py migrate --from-diff BASE [--head REV] [--wp WP-n] [--dry-run]
        For a branch that still edited the old single-file ledgers: diff the
        ledgers BASE..REV entry by entry, write the added entries as new
        fragments and apply edits of existing entries to their fragments.
    python ci/ledger.py roundtrip [--ref REV]
        Prove build(split(ledgers)) has the same entries and template as the
        ledgers (the source the stubs record, or REV). Also run by
        ci/test_ledger.py.
"""

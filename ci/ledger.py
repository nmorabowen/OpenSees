STUB_TITLES = {
    "implementations": "Ledger — our own implementations",
    "quirks": "Ledger — OpenSees quirks & gotchas",
    "vanilla": "Ledger — vanilla files we touched",
}


def render_stub(kind: str, source: str) -> str:
    led = KINDS[kind]["ledger"]
    return (
        f"---\ntitle: {STUB_TITLES[kind]} (stub)\nproject: Ladruno\ntags:\n  - ledger\n---\n\n"
        f"# {STUB_TITLES[kind]}\n\n"
        f"This file is a stub. Since WP-161 the ledger is one fragment per entry in\n"
        f"[`ledger/{kind}/`](ledger/{kind}/), named `WP-<nnn>-<slug>.md`.\n"
        f"**Never edit this file**; write a fragment (format: [`ledger/README.md`](ledger/README.md)).\n\n"
        f"- Read: `rg <pattern> Ladruno_implementation/ledger/{kind}/`\n"
        f"- Full ledger: `python ci/ledger.py build` writes `Ladruno_implementation/ledger/_build/{led}`\n"
        f"  (gitignored; CI uploads it as the `ledgers` artifact of the static-gates job).\n\n"
        f"<!-- ledger-stub kind={kind} split-source={source} -->\n"
    )


def stub_source(text: str) -> str | None:
    m = STUB_SOURCE_RE.search(text)
    return m.group(2) if m else None



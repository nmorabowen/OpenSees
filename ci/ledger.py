def git(root: Path, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", "-C", str(root), *args], stdin=subprocess.DEVNULL,
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    if check and r.returncode != 0:
        raise LedgerError(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout


def git_show(root: Path, rev: str, path: str) -> str:
    return git(root, "show", f"{rev}:{path}").replace("\r\n", "\n")


def ledger_source(root: Path, kind: str, ref: str | None = None) -> tuple[str, str]:
    """(text of the full single-file ledger, where it came from). REF if given;
    else the working tree when it is still a full ledger; else the split source
    the stub records."""
    path = f"{IMPL_DIR}/{KINDS[kind]['ledger']}"
    if ref:
        return git_show(root, ref, path), ref
    p = root / path
    text = p.read_text(encoding="utf-8").replace("\r\n", "\n") if p.exists() else ""
    if text and STUB_MARK not in text:
        return text, "worktree"
    src = stub_source(text)
    if not src or src == "worktree":
        raise LedgerError(f"{path} is a stub without a git split source; pass --ref")
    return git_show(root, src, path), src



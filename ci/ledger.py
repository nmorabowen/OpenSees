def roundtrip(kind: str, text: str) -> list[str]:
    """Problems (empty = proof holds) with build(split(text)) vs text."""
    tpl, entries = parse_ledger(kind, text)
    frags = split_entries(kind, entries, set())
    # through the file format too: dump + parse every fragment
    frags = [Fragment(kind, f.name, *parse_fragment(f.text())) for f in frags]
    rebuilt = render(kind, tpl, frags)
    tpl2, entries2 = parse_ledger(kind, rebuilt)
    problems = []
    if tpl2 != tpl:
        diff = "\n".join(difflib.unified_diff(tpl.split("\n"), tpl2.split("\n"), lineterm="", n=1))
        problems.append(f"{kind}: template differs after the round trip:\n{diff[:2000]}")
    a = Counter((e.section, e.text) for e in entries)
    b = Counter((e.section, e.text) for e in entries2)
    for (sec, t), k in (a - b).items():
        problems.append(f"{kind}: entry lost ({sec}, x{k}): {t[:120]!r}")
    for (sec, t), k in (b - a).items():
        problems.append(f"{kind}: entry gained ({sec}, x{k}): {t[:120]!r}")
    return problems


def cmd_split(root: Path, ref: str | None) -> int:
    source = ref or "worktree"
    if not ref:
        try:
            dirty = git(root, "status", "--porcelain", "--", *(f"{IMPL_DIR}/{s['ledger']}" for s in KINDS.values()))
            source = "worktree" if dirty.strip() else git(root, "rev-parse", "HEAD").strip()
        except (LedgerError, OSError):
            source = "worktree"
    texts = {}
    for kind, spec in KINDS.items():           # validate all three before writing anything
        path = root / IMPL_DIR / spec["ledger"]
        text = git_show(root, ref, f"{IMPL_DIR}/{spec['ledger']}") if ref else path.read_text(encoding="utf-8")
        if STUB_MARK in text:
            raise LedgerError(f"{spec['ledger']} is already a stub -- the split has been done. "
                              "To capture rows added since, use `migrate`.")
        problems = roundtrip(kind, text)
        if problems:
            raise LedgerError("round trip fails, nothing written:\n" + "\n".join(problems))
        texts[kind] = text
    for kind, spec in KINDS.items():
        path = root / IMPL_DIR / spec["ledger"]
        tpl, entries = parse_ledger(kind, texts[kind])
        d = frag_dir(root, kind)
        d.mkdir(parents=True, exist_ok=True)
        kept = []
        for f in load_fragments(root, kind):
            if f.legacy:
                f.path.unlink()             # a previous split's output: regenerate it
            else:
                kept.append(f)
        taken = {f.name.lower() for f in kept}
        frags = split_entries(kind, entries, taken)
        (d / TEMPLATE).write_text(tpl, encoding="utf-8", newline="\n")
        for f in frags:
            (d / f"{f.name}.md").write_text(f.text(), encoding="utf-8", newline="\n")
        path.write_text(render_stub(kind, source), encoding="utf-8", newline="\n")
        print(f"split {spec['ledger']}: {len(entries)} entries -> {len(frags)} fragments "
              f"(+{len(kept)} kept) in {d.relative_to(root).as_posix()}/")
    print(f"split source: {source}")
    return 0


def _identity(kind: str, e: Entry) -> str:
    if kind == "quirks":
        return e.text.split("\n", 1)[0].strip()
    c = cells(e.text) if is_row(e.text) else [e.text[:80]]
    if kind == "vanilla":
        return f"{e.section}|{' '.join(c[0].split()) if c else ''}|{' '.join(c[-1].split()) if c else ''}"
    return f"{e.section}|{plain(c[0])[:100] if c else ''}"


def plan_migration(kind: str, base_text: str, head_text: str, frags: list[Fragment],
                   wp: str, date: str, taken: set[str]):
    """-> (new fragments, [(fragment, new body)], [messages for a human])."""
    _, base = parse_ledger(kind, base_text)
    tpl_head, head = parse_ledger(kind, head_text)
    tpl_base, _ = parse_ledger(kind, base_text)
    notes = []
    if tpl_head != tpl_base:
        notes.append(f"{kind}: the intro/conventions text changed; edit ledger/{kind}/_template.md by hand")
    a = Counter((e.section, e.text) for e in base)
    b = Counter((e.section, e.text) for e in head)
    removed = [Entry(s, t) for (s, t), k in (a - b).items() for _ in range(k)]
    added = [Entry(s, t) for (s, t), k in (b - a).items() for _ in range(k)]
    edits, new_entries = [], []
    for e in added:
        same = [r for r in removed if r.section == e.section and _identity(kind, r) == _identity(kind, e)]
        if not same:
            scored = sorted(((difflib.SequenceMatcher(None, r.text, e.text).quick_ratio(), i)
                             for i, r in enumerate(removed) if r.section == e.section), reverse=True)
            scored = [(s, i) for s, i in scored if s >= 0.6 and
                      difflib.SequenceMatcher(None, removed[i].text, e.text).ratio() >= 0.6]
            same = [removed[scored[0][1]]] if scored else []
        if not same:
            new_entries.append(e)
            continue
        old = same[0]
        removed.remove(old)
        owner = next((f for f in frags if old.text in f.body.split("\n") or f.body == old.text), None)
        if owner is None:
            notes.append(f"{kind}: an edited entry has no fragment holding its old text; add by hand: {e.text[:120]!r}")
            continue
        if kind == "vanilla":
            body = "\n".join(e.text if r == old.text else r for r in owner.body.split("\n"))
        else:
            body = e.text
        edits.append((owner, body))
    for r in removed:
        notes.append(f"{kind}: an entry was DELETED on the branch; delete or retract its fragment by hand: {r.text[:120]!r}")
    new: list[Fragment] = []
    if kind == "vanilla":
        by_table: dict[str, list[str]] = {}
        for e in new_entries:
            by_table.setdefault(e.section, []).append(e.text)
        for table, rows in by_table.items():
            pr_cells = {" ".join(cells(r)[-1].split()) for r in rows if cells(r)}
            meta = {"wp": wp, "title": f"{wp} vanilla rows" + ("" if table == "main" else " (upstreamable)"),
                    "date": date, "files": [cells(r)[0] for r in rows], "table": table}
            prs = sorted({int(x) for c in pr_cells for x in PR_IN.findall(c)})
            if prs:
                meta["pr"] = ", ".join(f"#{p}" for p in prs)
            name = _unique(f"{wp}-vanilla" + ("" if table == "main" else "-upstreamable"), taken)
            new.append(Fragment(kind, name, meta, "\n".join(rows)))
    else:
        for e in new_entries:
            meta = impl_meta(e.text, e.section if e.section == "history" else "table") \
                if kind == "implementations" else quirk_meta(e.text)
            meta["wp"] = wp
            meta["date"] = date
            if kind == "implementations" and e.section != "history":
                meta.setdefault("status", "draft")
            new.append(Fragment(kind, _name(wp, meta["title"], taken), meta, e.text))
    return new, edits, notes


def _branch_wp(root: Path) -> str | None:
    try:
        br = git(root, "rev-parse", "--abbrev-ref", "HEAD").strip()
    except LedgerError:
        return None
    m = re.match(r"^wp/(\d{1,4}[a-z]?)-", br)
    return f"WP-{m.group(1)}" if m else None


def cmd_migrate(root: Path, base: str, head: str, wp: str | None, dry: bool) -> int:
    wp = wp or _branch_wp(root)
    if not wp or not KEY_RE.match(wp):
        raise LedgerError("cannot tell the WP key; pass --wp WP-<n>")
    date = _dt.date.today().isoformat()
    any_change = False
    for kind, spec in KINDS.items():
        path = f"{IMPL_DIR}/{spec['ledger']}"
        base_text = git_show(root, base, path)
        head_text = git_show(root, head, path)
        if STUB_MARK in head_text:
            print(f"{spec['ledger']}: already a stub at {head} -- nothing to migrate")
            continue
        frags = load_fragments(root, kind)
        taken = {f.name.lower() for f in frags}
        new, edits, notes = plan_migration(kind, base_text, head_text, frags, wp, date, taken)
        for f in new:
            any_change = True
            p = frag_dir(root, kind) / f"{f.name}.md"
            print(f"{'would write' if dry else 'write'} {p.relative_to(root).as_posix()}")
            if not dry:
                p.write_text(f.text(), encoding="utf-8", newline="\n")
        for f, body in edits:
            any_change = True
            print(f"{'would edit' if dry else 'edit'} {f.path.relative_to(root).as_posix()}")
            if not dry:
                f.path.write_text(dump_fragment(f.meta, body), encoding="utf-8", newline="\n")
        for n in notes:
            print("MANUAL " + n)
    if not any_change:
        print("migrate: no ledger entries added or edited between the two revisions")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Per-WP ledger fragments (WP-161).")
    ap.add_argument("--root", type=Path, default=ROOT)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="render LEDGER_*.md into ledger/_build/")
    b.add_argument("--out", type=Path)
    s = sub.add_parser("split", help="one-time migration of the single-file ledgers")
    s.add_argument("--ref", help="split the ledgers at this revision instead of the working tree")
    m = sub.add_parser("migrate", help="turn a branch's single-file ledger edits into fragments")
    m.add_argument("--from-diff", required=True, metavar="BASE", help="the revision the branch forked from")
    m.add_argument("--head", default="HEAD")
    m.add_argument("--wp", help="WP key for new fragments (default: from the wp/<n>-... branch name)")
    m.add_argument("--dry-run", action="store_true")
    r = sub.add_parser("roundtrip", help="prove build(split(ledgers)) == ledgers")
    r.add_argument("--ref")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    try:
        if args.cmd == "build":
            for kind, p in build(root, args.out).items():
                print(f"built {p.relative_to(root).as_posix() if p.is_relative_to(root) else p} "
                      f"({len(load_fragments(root, kind))} fragments)")
            return 0
        if args.cmd == "split":
            return cmd_split(root, args.ref)
        if args.cmd == "migrate":
            return cmd_migrate(root, args.from_diff, args.head, args.wp, args.dry_run)
        if args.cmd == "roundtrip":
            bad = []
            for kind in KINDS:
                text, src = ledger_source(root, kind, args.ref)
                probs = roundtrip(kind, text)
                print(f"roundtrip {kind} ({src}): {'OK' if not probs else 'FAIL'}")
                bad += probs
            for p in bad:
                print(p)
            return 1 if bad else 0
    except LedgerError as e:
        print(f"ledger: ERROR {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())

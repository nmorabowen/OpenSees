from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IMPL_DIR = "Ladruno_implementation"
FRAG_DIR = f"{IMPL_DIR}/ledger"
BUILD_DIR = f"{FRAG_DIR}/_build"
TEMPLATE = "_template.md"

KINDS = {
    "implementations": {"ledger": "LEDGER_implementations.md", "tables": ("table",),
                        "history": "## Documentation / ADR PRs"},
    "quirks": {"ledger": "LEDGER_quirks.md", "anchor": "## Quirks"},
    "vanilla": {"ledger": "LEDGER_vanilla_files.md", "tables": ("main", "upstreamable")},
}

# front-matter keys, in the order they are written
KEYS = ("wp", "title", "pr", "date", "status", "files", "class_tags", "banner",
        "section", "table", "legacy_seq")
KEY_RE = re.compile(r"^(WP-\d{1,4}[a-z]?|ADR-\d{1,4}[a-z]?|PR-\d{1,4}|LEGACY)$")
NAME_RE = re.compile(r"^(?P<key>WP-\d{1,4}[a-z]?|ADR-\d{1,4}[a-z]?|PR-\d{1,4}|LEGACY)-(?P<slug>[a-z0-9]+(?:-[a-z0-9]+)*)$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

GENERATED = "<!-- GENERATED by `python ci/ledger.py build` from Ladruno_implementation/ledger/{kind}/ -- do not edit; write a fragment -->"
GENERATED_RE = re.compile(r"^<!-- GENERATED by `python ci/ledger.py build`.*-->$")
STUB_MARK = "<!-- ledger-stub"
STUB_SOURCE_RE = re.compile(r"<!-- ledger-stub kind=(\w+) split-source=([0-9a-f]{7,40}|worktree) -->")
PLACEHOLDER_RE = re.compile(r"^<!-- ledger:(rows|history|entries)(?: ([\w-]+))? -->$")

SEP_RE = re.compile(r"^\|(?:\s*:?-{3,}:?\s*\|)+\s*$")
HEADING_RE = re.compile(r"^#{2,3} \S")
FENCE_RE = re.compile(r"^\s*(```|~~~)")
CELL_SPLIT = re.compile(r"(?<!\\)\|")
WP_IN = re.compile(r"\bWP[- ](\d{1,4}[a-z]?)\b")
ADR_IN = re.compile(r"\bADR[- ]?(\d{1,4}[a-z]?)\b")
PR_IN = re.compile(r"(?:/pull/|#)(\d{1,4})\b")


class LedgerError(RuntimeError):
    pass


# --------------------------------------------------------------------------
# fragments: front matter (a strict YAML subset) + body
# --------------------------------------------------------------------------
@dataclass
class Fragment:
    kind: str
    name: str                   # file stem
    meta: dict
    body: str
    path: Path | None = None

    @property
    def legacy(self) -> bool:
        return "legacy_seq" in self.meta

    def text(self) -> str:
        return dump_fragment(self.meta, self.body)


def _scalar(raw: str):
    """A front-matter value: JSON (quoted string, number, list, true/false/null) or a bare string."""
    if raw == "":
        return ""
    if raw[0] in "[{\"" or raw in ("true", "false", "null") or re.fullmatch(r"-?\d+", raw):
        try:
            return json.loads(raw)
        except json.JSONDecodeError as e:
            raise LedgerError(f"bad front-matter value {raw!r}: {e}") from None
    if raw[0] in "'&*!|>%@`#" or ": " in raw or " #" in raw:
        raise LedgerError(f"bare front-matter value {raw!r} is not plain YAML; quote it as JSON")
    return raw


def parse_fragment(text: str) -> tuple[dict, str]:
    """(meta, body). Front matter: `key: value` lines between two `---` lines."""
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0] != "---":
        raise LedgerError("no front matter (the first line must be ---)")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise LedgerError("front matter is not closed by a --- line") from None
    meta: dict = {}
    for ln in lines[1:end]:
        if not ln.strip():
            continue
        m = re.match(r"^([a-z_]+):(?: (.*))?$", ln)
        if not m:
            raise LedgerError(f"bad front-matter line {ln!r} (one `key: value` per line)")
        key = m.group(1)
        if key in meta:
            raise LedgerError(f"front-matter key {key!r} given twice")
        meta[key] = _scalar((m.group(2) or "").strip())
    return meta, "\n".join(lines[end + 1:]).strip("\n")


def _dump_value(v) -> str:
    if isinstance(v, str) and (DATE_RE.match(v) or KEY_RE.match(v)):
        return v
    return json.dumps(v, ensure_ascii=False)


def dump_fragment(meta: dict, body: str) -> str:
    keys = [k for k in KEYS if k in meta] + sorted(k for k in meta if k not in KEYS)
    head = "\n".join(f"{k}: {_dump_value(meta[k])}" for k in keys)
    return f"---\n{head}\n---\n{body.strip(chr(10))}\n"


def frag_dir(root: Path, kind: str) -> Path:
    return root / FRAG_DIR / kind


def load_fragments(root: Path, kind: str) -> list[Fragment]:
    out = []
    d = frag_dir(root, kind)
    if not d.is_dir():
        return out
    for p in sorted(d.glob("*.md")):
        if p.name.startswith("_"):
            continue
        meta, body = parse_fragment(p.read_text(encoding="utf-8"))
        out.append(Fragment(kind, p.stem, meta, body, p))
    return out


def load_template(root: Path, kind: str) -> str:
    p = frag_dir(root, kind) / TEMPLATE
    if not p.exists():
        raise LedgerError(f"{p.relative_to(root).as_posix()} is missing (run `python ci/ledger.py split` once)")
    return p.read_text(encoding="utf-8").replace("\r\n", "\n")


# --------------------------------------------------------------------------
# markdown helpers
# --------------------------------------------------------------------------
def is_row(line: str) -> bool:
    return line.startswith("|")


def cells(row: str) -> list[str]:
    parts = CELL_SPLIT.split(row.strip())
    if parts and parts[0] == "":
        parts = parts[1:]
    if parts and parts[-1].strip() == "":
        parts = parts[:-1]
    return [c.strip() for c in parts]


def plain(md: str) -> str:
    """Markdown -> plain text, for titles."""
    s = re.sub(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", lambda m: m.group(2) or m.group(1), md)
    s = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", s)
    s = s.replace("**", "").replace("`", "").replace("\\|", "|")
    s = re.sub(r"^#+\s*", "", s)
    return " ".join(s.split())


def shorten(s: str, n: int = 160) -> str:
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def slugify(s: str, n: int = 48) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    if len(s) > n:
        s = s[:n].rsplit("-", 1)[0] if "-" in s[:n] else s[:n]
    return s.strip("-") or "entry"


def _key_from(*texts: str) -> str | None:
    for rx, fmt in ((WP_IN, "WP-{}"), (ADR_IN, "ADR-{}")):
        for t in texts:
            m = rx.search(t or "")
            if m:
                return fmt.format(m.group(1))
    return None


def _pr_from(*texts: str) -> str | None:
    for t in texts:
        m = PR_IN.search(t or "")
        if m:
            return f"PR-{m.group(1)}"
    return None


def wp_number(key: str) -> int:
    m = re.match(r"^WP-(\d+)", key or "")
    return int(m.group(1)) if m else 0


# --------------------------------------------------------------------------
# parse a single-file ledger into (template, entries)
# --------------------------------------------------------------------------
@dataclass
class Entry:
    section: str        # rows table name / "history" / "entries"
    text: str
    meta: dict = field(default_factory=dict)


def _collapse_blank(lines: list[str]) -> str:
    out: list[str] = []
    for ln in lines:
        if ln.strip() == "" and out and out[-1].strip() == "":
            continue
        out.append(ln)
    while out and out[-1].strip() == "":
        out.pop()
    return "\n".join(out) + "\n"


def _strip_generated(lines: list[str]) -> list[str]:
    return [ln for ln in lines if not GENERATED_RE.match(ln.strip())]


def parse_ledger(kind: str, text: str) -> tuple[str, list[Entry]]:
    """Split a whole ledger file into its template (everything that is not an
    entry, with placeholders where the entries go) and its entries, in order."""
    if STUB_MARK in text:
        raise LedgerError(f"{KINDS[kind]['ledger']} is a stub, not a ledger -- nothing to parse")
    lines = _strip_generated(text.replace("\r\n", "\n").split("\n"))
    if kind == "quirks":
        return _parse_quirks(lines)
    return _parse_tables(kind, lines)


def _parse_quirks(lines: list[str]) -> tuple[str, list[Entry]]:
    anchor = KINDS["quirks"]["anchor"]
    try:
        q = next(i for i, ln in enumerate(lines) if ln.rstrip() == anchor)
    except StopIteration:
        raise LedgerError(f"quirks ledger has no '{anchor}' heading") from None
    tpl = lines[: q + 1]
    entries: list[Entry] = []
    cur: list[str] | None = None
    fence = None
    for ln in lines[q + 1:]:
        fm = FENCE_RE.match(ln)
        if fm:
            fence = None if fence == fm.group(1) else (fence or fm.group(1))
        if fence is None and not fm and HEADING_RE.match(ln):
            if cur is not None:
                entries.append(Entry("entries", "\n".join(cur).strip("\n")))
            cur = [ln]
            continue
        if cur is None:
            if ln.strip():
                tpl.append(ln)              # prose between the anchor and the first entry
            continue
        cur.append(ln)
    if cur is not None:
        entries.append(Entry("entries", "\n".join(cur).strip("\n")))
    tpl += ["", "<!-- ledger:entries -->"]
    return _collapse_blank(tpl), entries


def _parse_tables(kind: str, lines: list[str]) -> tuple[str, list[Entry]]:
    names = KINDS[kind]["tables"]
    history = KINDS[kind].get("history")
    tpl: list[str] = []
    entries: list[Entry] = []
    in_ledger = False           # past the first "## Ledger" heading
    ti = -1                     # index of the current/last ledger table
    mode = None                 # None | "table" | "history"
    in_history = False
    history_placed = False
    i, n = 0, len(lines)

    def plain_row_follows(k):
        """True if the next non-blank line after k is a row that does not open a new table."""
        while k < n and not lines[k].strip():
            k += 1
        return k < n and is_row(lines[k]) and not (k + 1 < n and SEP_RE.match(lines[k + 1]))

    while i < n:
        ln = lines[i]
        if not in_ledger and ln.rstrip() == "## Ledger":
            in_ledger = True
        if history and ln.startswith(history):
            in_history = True
        # a ledger table starts: header row + separator
        if in_ledger and mode != "table" and ti + 1 < len(names) and is_row(ln) \
                and i + 1 < n and SEP_RE.match(lines[i + 1]):
            ti += 1
            tpl += [ln, lines[i + 1], f"<!-- ledger:rows {names[ti]} -->"]
            mode = "table"
            i += 2
            continue
        if mode == "table":
            if is_row(ln):
                entries.append(Entry(names[ti], ln.rstrip()))
                i += 1
                continue
            if not ln.strip() and plain_row_follows(i):
                i += 1                  # a blank line inside the table (a union-merge artefact)
                continue
            mode = None
        if mode == "history":
            if ln.startswith((" ", "\t")) and ln.strip():
                entries[-1].text += "\n" + ln.rstrip()
                i += 1
                continue
            mode = None
        if ti >= 0 and is_row(ln) and not (i + 1 < n and SEP_RE.match(lines[i + 1])):
            entries.append(Entry(names[ti], ln.rstrip()))      # an orphan row appended past the table
            i += 1
            continue
        if in_history and ln.startswith("- "):
            if not history_placed:
                tpl.append("<!-- ledger:history -->")
                history_placed = True
            entries.append(Entry("history", ln.rstrip()))
            mode = "history"
            i += 1
            continue
        if ti >= 0 and not ln.strip() and plain_row_follows(i):
            i += 1                      # blank lines between orphan rows
            continue
        tpl.append(ln)
        i += 1
    if ti + 1 != len(names):
        raise LedgerError(f"{KINDS[kind]['ledger']}: found {ti + 1} ledger table(s), expected {len(names)}")
    return _collapse_blank(tpl), entries


# --------------------------------------------------------------------------
# split: entries -> fragments
# --------------------------------------------------------------------------
def _unique(name: str, taken: set[str]) -> str:
    base, k = name, 2
    while name.lower() in taken:
        name = f"{base}-{k}"
        k += 1
    taken.add(name.lower())
    return name


def _name(key: str, title: str, taken: set[str]) -> str:
    t = title
    if key != "LEGACY":
        num = key.split("-", 1)[1]
        prefix = "(?:PR[- ]?|#)" if key.startswith("PR-") else key.split("-")[0] + "[- ]?"
        t = re.sub(r"^\W*" + prefix + re.escape(num) + r"\b\W*", "", t, flags=re.I)
    return _unique(f"{key}-{slugify(t)}", taken)


def impl_meta(text: str, section: str) -> dict:
    """Front matter for one implementations row or history bullet."""
    if section == "history":
        title = plain(text[2:])
        key = _key_from(text[:300]) or _pr_from(text[:200]) or "LEGACY"
        return {"wp": key, "title": shorten(title, 120), "section": "history"}
    c = cells(text)
    feature = c[0] if c else text
    bold = re.match(r"^\s*\*\*(.+?)\*\*", feature)
    title = plain(bold.group(1) if bold else feature)
    pr_cell = c[-1] if len(c) >= 2 else ""
    key = _key_from(feature) or _pr_from(pr_cell) or _key_from(text) or "LEGACY"
    meta = {"wp": key, "title": shorten(title)}
    prs = sorted({int(x) for x in PR_IN.findall(pr_cell)})
    if prs:
        meta["pr"] = ", ".join(f"#{p}" for p in prs)
    if len(c) == 6:
        meta["status"] = shorten(plain(c[4]), 80)
        tags = sorted(set(re.findall(r"\b[A-Z][A-Z0-9]*_TAG_\w+", c[2])))
        if tags:
            meta["class_tags"] = tags
    meta["section"] = "table"
    return meta


def quirk_meta(text: str) -> dict:
    head = text.split("\n", 1)[0]
    title = plain(head)
    key = _key_from(head) or _pr_from(head) or "LEGACY"     # the heading only: a body cites other WPs
    meta = {"wp": key, "title": shorten(title)}
    d = re.search(r"\b(20\d\d-\d\d-\d\d)\b", head)
    if d:
        meta["date"] = d.group(1)
    return meta


def split_entries(kind: str, entries: list[Entry], taken: set[str]) -> list[Fragment]:
    """Fragments for migrated entries, `legacy_seq` = position in the old file."""
    frags: list[Fragment] = []
    if kind in ("implementations", "quirks"):
        for seq, e in enumerate(entries, 1):
            meta = impl_meta(e.text, "history" if e.section == "history" else "table") \
                if kind == "implementations" else quirk_meta(e.text)
            meta["legacy_seq"] = seq
            name = _name(meta["wp"], meta["title"], taken)
            frags.append(Fragment(kind, name, meta, e.text))
        return frags
    # vanilla: one fragment per (table, PR cell); rows keep their own positions
    groups: dict[tuple[str, str], list[tuple[int, str]]] = {}
    for seq, e in enumerate(entries, 1):
        c = cells(e.text)
        pr_cell = " ".join(c[-1].split()) if len(c) >= 2 else ""
        groups.setdefault((e.section, pr_cell), []).append((seq, e.text))
    for (table, pr_cell), rows in groups.items():
        whys = {m for _, r in rows for m in WP_IN.findall(" ".join(cells(r)[1:-1]))}
        key = _key_from(pr_cell) if WP_IN.search(pr_cell) else None
        if key is None and len(whys) == 1:
            key = f"WP-{next(iter(whys))}"
        bare = re.fullmatch(r"#?(\d{1,4})", plain(pr_cell))
        key = key or _pr_from(pr_cell) or (f"PR-{bare.group(1)}" if bare else None) \
            or _key_from(pr_cell) or "LEGACY"
        files = [cells(r)[0] if cells(r) else "" for _, r in rows]
        title = plain(pr_cell) or "no PR recorded"
        meta = {"wp": key, "title": shorten(f"{title} -- {len(rows)} vanilla row(s)" if table == "main"
                                            else f"{title} -- upstreamable-table row(s)"),
                "files": files, "table": table, "legacy_seq": [s for s, _ in rows]}
        prs = sorted({int(x) for x in PR_IN.findall(pr_cell)} | ({int(bare.group(1))} if bare else set()))
        if prs:
            meta["pr"] = ", ".join(f"#{p}" for p in prs)
        # slug: what the PR cell says besides the PR link; else the first file's name
        what = re.sub(r"\[#?\d+\]\([^)]*\)|#\d+\b|^\d+$", " ", plain(re.sub(r"\[([^\]]*)\]\([^)]*\)", " ", pr_cell)))
        what = re.sub(r"^\W*" + re.escape(key) + r"\b", " ", what.strip(), flags=re.I)
        if not slugify(what, 40).strip("-") or slugify(what, 40) == "entry":
            what = Path(plain(files[0]).split(",")[0].split(" ")[0].strip("{}")).name or "rows"
        name = _name(key, what + ("" if table == "main" else " upstreamable"), taken)
        frags.append(Fragment("vanilla", name, meta, "\n".join(r for _, r in rows)))
    return frags


# --------------------------------------------------------------------------
# build: fragments -> ledger text
# --------------------------------------------------------------------------
def _new_key(f: Fragment):
    return (f.meta.get("date") or "", wp_number(f.meta.get("wp", "")), f.name)


def render(kind: str, template: str, frags: list[Fragment]) -> str:
    legacy = [f for f in frags if f.legacy]
    new = [f for f in frags if not f.legacy]
    blocks: dict[tuple[str, str], list[str]] = {}

    def seq(f):
        s = f.meta["legacy_seq"]
        return s[0] if isinstance(s, list) else s

    if kind == "quirks":
        ordered = sorted(new, key=_new_key, reverse=True) + sorted(legacy, key=seq)
        blocks[("entries", "")] = [f.body for f in ordered]
    elif kind == "implementations":
        rows_new = sorted((f for f in new if f.meta.get("section", "table") == "table"), key=_new_key, reverse=True)
        rows_old = sorted((f for f in legacy if f.meta.get("section", "table") == "table"), key=seq)
        hist_old = sorted((f for f in legacy if f.meta.get("section") == "history"), key=seq)
        hist_new = sorted((f for f in new if f.meta.get("section") == "history"), key=_new_key)
        blocks[("rows", "table")] = [f.body for f in rows_new + rows_old]
        blocks[("history", "")] = [f.body for f in hist_old + hist_new]
    else:
        per_table: dict[str, list[tuple[tuple, str, str]]] = {}
        for f in frags:
            table = f.meta.get("table", "main")
            rows = [r for r in f.body.split("\n") if r.strip()]
            seqs = f.meta.get("legacy_seq")
            for k, r in enumerate(rows):
                if f.legacy:
                    order = (0, seqs[k] if isinstance(seqs, list) and k < len(seqs) else seq(f), "", 0, "", k)
                else:
                    order = (1, 0, f.meta.get("date") or "", wp_number(f.meta.get("wp", "")), f.name, k)
                c = cells(r)
                per_table.setdefault(table, []).append((order, " ".join((c[0] if c else r).split()), r))
        for table, rows in per_table.items():
            first: dict[str, tuple] = {}
            for order, fk, _ in rows:
                if fk not in first or order < first[fk]:
                    first[fk] = order
            rows.sort(key=lambda t: (first[t[1]], t[0]))
            blocks[("rows", table)] = [r for _, _, r in rows]

    out: list[str] = []
    seen = set()
    for ln in template.replace("\r\n", "\n").rstrip("\n").split("\n"):
        m = PLACEHOLDER_RE.match(ln.strip())
        if not m:
            out.append(ln)
            continue
        key = (m.group(1), m.group(2) or "")
        seen.add(key)
        body = blocks.get(key, [])
        if m.group(1) == "entries":
            out.append("\n\n".join(body))
        else:
            out.extend(body)
    missing = [k for k, v in blocks.items() if v and k not in seen]
    if missing:
        raise LedgerError(f"{kind}: _template.md has no placeholder for {missing}")
    text = "\n".join(out).rstrip("\n") + "\n"
    # the GENERATED banner goes right after the front matter
    lines = text.split("\n")
    at = 0
    if lines and lines[0] == "---" and "---" in lines[1:]:
        at = lines.index("---", 1) + 1
    lines.insert(at, GENERATED.format(kind=kind))
    return "\n".join(lines)


def build(root: Path, out_dir: Path | None = None) -> dict[str, Path]:
    out_dir = out_dir or root / BUILD_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    written = {}
    for kind, spec in KINDS.items():
        text = render(kind, load_template(root, kind), load_fragments(root, kind))
        p = out_dir / spec["ledger"]
        p.write_text(text, encoding="utf-8", newline="\n")
        written[kind] = p
    return written


